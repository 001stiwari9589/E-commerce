  if (pCat === sCat) return true;

  const aliases = {
    mobiles: ['mobile', 'mobiles', 'mobile accessories', 'smartphones', 'phone'],
    electronics: ['electronics', 'audio', 'computer accessories', 'gadgets'],
    fashion: ['fashion', 'clothing', 'apparel', 'accessories'],
    footwear: ['footwear', 'shoes', 'sneakers'],
    home: ['home', 'home and kitchen', 'kitchen', 'living'],
    appliances: ['appliances', 'home appliances'],
    beauty: ['beauty', 'personal care', 'cosmetics', 'toys'],
    toys: ['toys', 'kids', 'beauty'],
    grocery: ['grocery', 'food', 'daily needs'],
    sports: ['sports', 'fitness', 'gym', 'workout'],
    books: ['books', 'stationery', 'student essentials', 'study'],
    gaming: ['gaming', 'gear', 'games'],
    jewelry: ['jewelry', 'watches', 'smartwatches'],
    automotive: ['automotive', 'car', 'bike', 'auto'],
    pets: ['pets', 'pet supplies', 'animals'],
  };

  const allowed = aliases[sCat] || [sCat];
